/**
 * Returns an SVG string for the given icon name.
 * @param {keyof typeof PATHS} name
 * @param {{size?: number, label?: string}} [options]
 *   `label` makes the icon accessible; without it the icon is decorative.
 * @returns {string}
 */
export function icon(name, { size = 18, label } = {}) {
  const body = PATHS[name] ?? PATHS.alert;
  const a11y = label
    ? `role="img" aria-label="${escapeAttr(label)}"`
    : 'aria-hidden="true"';
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" ` +
    `viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ` +
    `stroke-linecap="round" stroke-linejoin="round" ${a11y}>${body}</svg>`
  );
}

/** @returns {string[]} All available icon names (used by tests / docs). */
export function iconNames() {
  return Object.keys(PATHS);
}

function escapeAttr(value) {
  return String(value).replace(/[&"<>]/g, (c) => `&#${c.charCodeAt(0)};`);
}
